/**
 * 広告を出してよいページかの判断（検索エンジンへの登録とは別に判断する）。
 * Google のパブリッシャー向けポリシーでは、衝撃的な内容（死傷・事件の描写など）は「制限」の対象で、
 * 性的な内容などは広告を出せない。ニュースとして読者に届ける価値はあるため、検索への登録は続け、広告だけを外す。
 * 見出し・リードの言葉で判断する（取りこぼしより、広告を出しすぎないことを優先する）
 */
export const AD_SENSITIVE =
  /死去|死亡|急死|訃報|亡くなっ|遺体|殺害|殺人|刺殺|自殺|死刑|処刑|心中|遺族|逮捕|容疑|書類送検|起訴|送検|わいせつ|性的|性被害|性暴力|盗撮|痴漢|不同意|強制性交|児童ポルノ|買春|売春|薬物|覚醒剤|大麻|虐待|暴行|監禁|誘拐|不倫|戦死|爆撃|テロ/;

/** 話題の見出し・リードが、広告を出すのに向かない内容か */
export function isAdSensitive(...texts: (string | null | undefined)[]): boolean {
  return texts.some((t) => !!t && AD_SENSITIVE.test(t.normalize("NFKC")));
}
